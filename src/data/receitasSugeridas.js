/**
 * Receitas sugeridas: biblioteca de receitas típicas de negócios caseiros de
 * comida no Brasil, usada para sugerir ingredientes quando o usuário digita o
 * nome de um produto (ex.: "bolo de pote de ninho com morango").
 *
 * - Quantidades são da receita INTEIRA (a fornada/panela que a pessoa faz em
 *   casa), não por porção. `rende` diz quantas porções a receita inteira dá.
 * - `porcao` é a unidade de venda [singular, plural]. Produtos vendidos por
 *   cento usam ['cento', 'centos'] e `rende` = quantos centos a receita dá.
 * - `embalagem` é UMA por porção: [nome, preço médio por unidade em R$], ou
 *   null quando o produto é vendido sem embalagem.
 * - Preços de ingredientes NÃO ficam aqui: vêm de src/data/marketPrices.js.
 *   Use o mesmo nome da base de preços sempre que for o mesmo produto (a
 *   comparação ignora acentos e maiúsculas). Ingrediente sem preço na base
 *   aparece como "sem preço" e o usuário preenche.
 * - `termos`: minúsculos, SEM acentos, comparados como trecho do nome digitado.
 *   O termo mais longo vence, então termos específicos (ex.: 'ninho com
 *   nutella') ficam na receita específica. Um termo não pode se repetir entre
 *   receitas.
 * - Unidades: só 'g', 'ml' ou 'un'.
 *
 * Para adicionar uma receita: copie um item do mesmo nicho, troque o `id`
 * (snake_case único), `nome`, `termos`, ingredientes e `rende`, e rode
 * `node --import ./__tests__/loader.mjs --test __tests__/receitasSugeridas.test.mjs`.
 */

